// ============ REGISTRY ============
async function loadRegistry() {
  try {
    const raw = await fsp.readFile(CONFIG.registryFile, 'utf8');
    return JSON.parse(raw);
  } catch {
    return { version: CONFIG.schemaVersion, skills: {}, updatedAt: nowIso() };
  }
}

async function saveRegistry(reg) {
  reg.updatedAt = nowIso();
  await atomicWrite(CONFIG.registryFile, JSON.stringify(reg, null, 2));
}

// ============ BACKUP ============
async function backupFile(file) {
  try {
    if (!fs.existsSync(file)) return null;
    await ensureDir(CONFIG.backupDir);
    const stamp = new Date().toISOString().replace(/[:.]/g, '-');
    const dest = path.join(
      CONFIG.backupDir,
      `${path.basename(file)}.${stamp}.bak`
    );
    await fsp.copyFile(file, dest);

    // Rotate
    const all = (await fsp.readdir(CONFIG.backupDir))
      .filter((f) => f.endsWith('.bak'))
      .sort();
    if (all.length > CONFIG.maxBackups) {
      for (const f of all.slice(0, all.length - CONFIG.maxBackups)) {
        await fsp.unlink(path.join(CONFIG.backupDir, f)).catch(() => {});
      }
    }
    return dest;
  } catch (err) {
    log('warn', 'backup failed', { err: err.message });
    return null;
  }
}

// ============ MAIN CLASS ============
class SkillBuilderAgent {
  constructor() {
    this.stats = {
      built: 0,
      saved: 0,
      updated: 0,
      deleted: 0,
      failed: 0,
      byTemplate: {},
      byCategory: {},
    };
  }

  /**
   * Build skill code (in-memory, no disk write).
   */
  buildSkill(skillName, options = {}) {
    const name = sanitize(skillName);
    if (!name) throw new Error('Invalid skill name');

    const templateKey = options.template || 'basic';
    const template = TEMPLATES[templateKey];
    if (!template) throw new Error(`Unknown template: ${templateKey}`);

    const description = options.description ||
      `${name} generated by SkillBuilderAgent`;
    const category = options.category || 'general';
    const version = options.version || CONFIG.defaultVersion;

    const code = template({
      name,
      description,
      category,
      version,
      options,
    });

    // Validate syntax
    if (CONFIG.validateSyntax) {
      const v = validateJsSyntax(code, `${name}.js`);
      if (!v.ok) {
        throw Object.assign(
          new Error(`Generated code has syntax error: ${v.error}`),
          { code: 'SYNTAX_ERROR' }
        );
      }
    }

    const result = {
      name,
      fileName: `${name}.js`,
      code,
      template: templateKey,
      category,
      description,
      version,
      generatedAt: nowIso(),
    };

    this.stats.built++;
    this.stats.byTemplate[templateKey] = (this.stats.byTemplate[templateKey] || 0) + 1;
    this.stats.byCategory[category] = (this.stats.byCategory[category] || 0) + 1;

    return result;
  }

  /**
   * Preview without writing.
   */
  preview(skillName, options = {}) {
    const built = this.buildSkill(skillName, options);
    return {
      ...built,
      preview: true,
      lines: built.code.split('\n').length,
    };
  }

  /**
   * Save skill to disk (with tests, docs, manifest).
   */
  async saveSkill(skillName, skillsDir, options = {}) {
    const dir = skillsDir || CONFIG.defaultSkillsDir;
    const built = this.buildSkill(skillName, options);

    const skillFile = path.join(dir, built.fileName);
    const manifestFile = path.join(dir, `${built.name}.manifest.json`);
    const testFile = path.join(
      options.testsDir || path.join(process.cwd(), 'tests'),
      `${built.name}.test.js`
    );
    const docFile = path.join(
      options.docsDir || path.join(dir, 'docs'),
      `${built.name}.md`
    );

    // Overwrite check
    if (fs.existsSync(skillFile) && CONFIG.overwritePolicy === 'reject' && !options.force) {
      return {
        success: false,
        error: `Skill already exists: ${skillFile}`,
        hint: 'Pass { force: true } or { overwrite: "backup" }',
      };
    }

    // Backup existing files
    const backups = [];
    if (fs.existsSync(skillFile)) {
      const b = await backupFile(skillFile);
      if (b) backups.push(b);
    }

    await ensureDir(dir);

    // Write skill file
    await atomicWrite(skillFile, built.code);

    const written = { skill: skillFile, extras: [] };

    // Tests
    if (options.tests !== false && CONFIG.generateTests) {
      const testCode = buildTestCode(built.name, built.template, built.version);
      await atomicWrite(testFile, testCode);
      written.extras.push({ type: 'test', file: testFile });
    }

    // Docs
    if (options.docs !== false && CONFIG.generateDocs) {
      const readme = buildReadme(built, {
        name: built.name,
        description: built.description,
        version: built.version,
        category: built.category,
        template: built.template,
        generatedAt: built.generatedAt,
        schema: options.schema || null,
      });
      await atomicWrite(docFile, readme);
      written.extras.push({ type: 'doc', file: docFile });
    }

    // Manifest
    if (options.manifest !== false && CONFIG.generateManifest) {
      const manifest = buildManifest({
        ...built,
        files: [skillFile, testFile, docFile].filter((f) => fs.existsSync(f)),
        dependencies: options.dependencies || [],
        tags: options.tags || [],
        author: options.author,
        schema: options.schema || null,
      });
      await atomicWrite(manifestFile, JSON.stringify(manifest, null, 2));
      written.extras.push({ type: 'manifest', file: manifestFile });
    }

    // Update registry
    const reg = await loadRegistry();
    const existing = reg.skills[built.name];
    reg.skills[built.name] = {
      name: built.name,
      version: built.version,
      category: built.category,
      template: built.template,
      description: built.description,
      file: skillFile,
      addedAt: existing?.addedAt || nowIso(),
      updatedAt: nowIso(),
    };
    await saveRegistry(reg);

    this.stats.saved++;
    if (existing) this.stats.updated++;

    log('info', 'skill saved', { name: built.name, file: skillFile });

    return {
      success: true,
      file: skillFile,
      name: built.name,
      version: built.version,
      backups,
      files: written,
      manifest: path.join(dir, `${built.name}.manifest.json`),
    };
  }

  /**
   * Bulk save multiple skills.
   */
  async saveMany(skillNames, skillsDir, options = {}) {
    const results = [];
    for (const name of skillNames) {
      try {
        results.push(await this.saveSkill(name, skillsDir, options));
      } catch (err) {
        this.stats.failed++;
        results.push({ success: false, name, error: err.message });
      }
    }
    return results;
  }

  /**
   * Update existing skill (keeps version bump).
   */
  async updateSkill(skillName, options = {}) {
    const dir = options.skillsDir || CONFIG.defaultSkillsDir;
    const existing = await this.getSkill(skillName);
    if (!existing) {
      return { success: false, error: 'Skill not found' };
    }

    const currentVersion = existing.version || '1.0.0';
    const nextVersion = bumpVersion(currentVersion, options.bump || 'patch');

    return this.saveSkill(skillName, dir, {
      ...options,
      version: nextVersion,
      force: true,
      overwrite: 'backup',
    });
  }

  /**
   * Delete a skill + its extras.
   */
  async deleteSkill(skillName, options = {}) {
    const name = sanitize(skillName);
    const dir = options.skillsDir || CONFIG.defaultSkillsDir;
    const files = [
      path.join(dir, `${name}.js`),
      path.join(dir, `${name}.manifest.json`),
      path.join(options.testsDir || path.join(process.cwd(), 'tests'), `${name}.test.js`),
      path.join(options.docsDir || path.join(dir, 'docs'), `${name}.md`),
    ];

    const deleted = [];
    const backups = [];

    for (const f of files) {
      if (!fs.existsSync(f)) continue;
      const b = await backupFile(f);
      if (b) backups.push(b);
      await fsp.unlink(f);
      deleted.push(f);
    }

    const reg = await loadRegistry();
    delete reg.skills[name];
    await saveRegistry(reg);

    this.stats.deleted++;
    log('info', 'skill deleted', { name, count: deleted.length });

    return { success: true, name, deleted, backups };
  }

  /**
   * List skills (from registry).
   */
  async listSkills(filter = {}) {
    const reg = await loadRegistry();
    let list = Object.values(reg.skills);

    if (filter.category) list = list.filter((s) => s.category === filter.category);
    if (filter.template) list = list.filter((s) => s.template === filter.template);
    if (filter.name) {
      const re = new RegExp(filter.name, 'i');
      list = list.filter((s) => re.test(s.name));
    }

    return list.sort((a, b) => a.name.localeCompare(b.name));
  }

  /**
   * Get one skill (from registry + filesystem).
   */
  async getSkill(skillName) {
    const reg = await loadRegistry();
    const meta = reg.skills[sanitize(skillName)];
    if (!meta) return null;

    try {
      const code = await fsp.readFile(meta.file, 'utf8');
      return { ...meta, code };
    } catch {
      return meta;
    }
  }

  /**
   * Verify skill loads & has expected shape.
   */
  async verifySkill(skillName, options = {}) {
    const path = options.file ||
      path.join(options.skillsDir || CONFIG.defaultSkillsDir, `${sanitize(skillName)}.js`);

    if (!fs.existsSync(path)) {
      return { ok: false, error: 'file not found', path };
    }

    // Syntax check
    const code = await fsp.readFile(path, 'utf8');
    const syn = validateJsSyntax(code, path);
    if (!syn.ok) return { ok: false, error: syn.error };

    // Load & shape check
    try {
      delete require.cache[require.resolve(path)];
      const mod = require(path);

      const issues = [];
      if (!mod.name) issues.push('missing name');
      if (!mod.description) issues.push('missing description');
      if (typeof mod.run !== 'function') issues.push('missing run()');
      if (typeof mod.health !== 'function') issues.push('(optional) missing health()');

      return {
        ok: issues.length === 0,
        name: mod.name,
        version: mod.version,
        issues,
        path,
      };
    } catch (err) {
      return { ok: false, error: err.message, path };
    }
  }

  /**
   * Verify all skills in registry.
   */
  async verifyAll(options = {}) {
    const list = await this.listSkills(options.filter || {});
    const results = [];
    for (const s of list) {
      results.push(await this.verifySkill(s.name, options));
    }
    return {
      ok: results.every((r) => r.ok),
      total: results.length,
      passed: results.filter((r) => r.ok).length,
      failed: results.filter((r) => !r.ok),
      results,
    };
  }

  /**
   * Detect if skill has missing dependencies.
   */
  async checkDependencies(skillName, options = {}) {
    const skill = await this.getSkill(skillName);
    if (!skill || !skill.code) return { ok: true, missing: [] };

    const deps = [];
    const re = /require\s*\(\s*['"]([^'"]+)['"]\s*\)/g;
    let m;
    while ((m = re.exec(skill.code))) deps.push(m[1]);

    const missing = [];
    for (const dep of deps) {
      if (dep.startsWith('.')) continue;    // local imports — skip
      try {
        require.resolve(dep, { paths: [process.cwd()] });
      } catch {
        missing.push(dep);
      }
    }

    return { ok: missing.length === 0, dependencies: deps, missing };
  }

  /**
   * Available templates.
   */
  listTemplates() {
    return Object.keys(TEMPLATES).map((key) => ({
      key,
      description: TEMPLATE_DESCRIPTIONS[key] || '',
    }));
  }

  /**
   * Stats.
   */
  getStats() {
    return { ...this.stats };
  }
}

