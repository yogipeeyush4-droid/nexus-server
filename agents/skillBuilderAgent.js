function buildReadme(skill, meta) {
  const lines = [];
  lines.push(`# 🧩 ${meta.name}`);
  lines.push('');
  lines.push(`> ${meta.description}`);
  lines.push('');
  lines.push(`**Version:** \`${meta.version}\`  `);
  lines.push(`**Category:** \`${meta.category}\`  `);
  lines.push(`**Template:** \`${meta.template}\`  `);
  lines.push(`**Generated:** ${meta.generatedAt}  `);
  lines.push('');
  lines.push('## 📦 Usage');
  lines.push('');
  lines.push('```js');
  lines.push(`const skill = require('./skills/${meta.name}.js');`);
  lines.push('');
  lines.push(`const result = await skill.run({ /* args */ });`);
  lines.push('console.log(result);');
  lines.push('```');
  lines.push('');

  if (meta.schema?.properties) {
    lines.push('## 🔤 Input Schema');
    lines.push('');
    lines.push('| Field | Type | Required |');
    lines.push('|---|---|---|');
    const required = new Set(meta.schema.required || []);
    for (const [k, v] of Object.entries(meta.schema.properties)) {
      lines.push(`| \`${k}\` | ${v.type || 'any'} | ${required.has(k) ? '✅' : '❌'} |`);
    }
    lines.push('');
  }

  lines.push('## 🧪 Testing');
  lines.push('');
  lines.push('```bash');
  lines.push(`node --test tests/${meta.name}.test.js`);
  lines.push('```');
  lines.push('');
  lines.push('---');
  lines.push(`_Generated by SkillBuilderAgent on ${meta.generatedAt}_`);
  return lines.join('\n');
}

