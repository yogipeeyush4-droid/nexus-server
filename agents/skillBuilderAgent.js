// ============ HELPERS ============
function uid(p = 's') {
  return `${p}_${crypto.randomBytes(4).toString('hex')}`;
}

function nowIso() {
  return new Date().toISOString();
}

function sanitize(name) {
  return String(name || '')
    .replace(/[^a-z0-9_-]/gi, '_')
    .replace(/_+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toLowerCase();
}

function toClassName(name) {
  return sanitize(name)
    .split(/[_-]/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join('');
}

function toPascalCase(name) {
  return toClassName(name);
}

async function ensureDir(dir) {
  await fsp.mkdir(dir, { recursive: true });
}

async function atomicWrite(file, data) {
  await ensureDir(path.dirname(file));
  const tmp = `${file}.tmp-${process.pid}-${Date.now()}`;
  await fsp.writeFile(tmp, data, 'utf8');
  await fsp.rename(tmp, file);
}

function validateJsSyntax(code, filename = 'skill.js') {
  try {
    // Use new Function to compile-check (avoid running)
    // eslint-disable-next-line no-new-func
    new Function('module', 'exports', 'require', code);
    return { ok: true };
  } catch (err) {
    return { ok: false, error: err.message, filename };
  }
}

