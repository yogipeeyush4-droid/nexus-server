// ============ VERSION BUMP ============
function bumpVersion(v, type = 'patch') {
  const [major, minor, patch] = String(v || '1.0.0')
    .split('.')
    .map((n) => parseInt(n, 10) || 0);

  if (type === 'major') return `${major + 1}.0.0`;
  if (type === 'minor') return `${major}.${minor + 1}.0`;
  return `${major}.${minor}.${patch + 1}`;
}

